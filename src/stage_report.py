"""One report that scores every stage SEPARATELY, so errors of one stage never hide in another.

End-to-end numbers mix stages: a wrong grounding box makes J&F, PSNR and LPIPS all bad,
even if the tracker and the fill did their jobs. This report separates them:

  1. Grounding   did the text prompt pick the right object on frame 0? (box IoU > 0.5)
  2. Tracking    J&F of the masks. Click prompt (B0) = tracking from a correct start;
                 for text versions also J&F on the clips grounding got right only.
  3. Fill        every fill method run on the TRUE masks (configs/fill_only.yaml), so
                 fill metrics measure filling only. Synthetic clips (needs the clean video).
  4. End to end  the full pipeline (results/results.csv), what a user would get.
  5. Metric check  do the fill metrics behave as claimed? (src/metric_check.py)

Reads only the CSVs the scripts wrote; writes results/stage_report.md.
    python -m src.stage_report
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

TEXT_VERSIONS = ["I2", "I2b", "I2c", "I5"]
FILL_VERSIONS = ["B0", "I1", "I3", "I3b", "I4"]
FILL_COLS = {"psnr_mask": "PSNR mask ↑", "lpips_mask": "LPIPS mask ↓", "ssim": "SSIM ↑",
             "flicker_raft": "Flicker RAFT ↓", "flicker_raft_ref": "(clean video)", "spf_inpaint": "Fill s/frame ↓"}


def read(path: str) -> pd.DataFrame:
    p = Path(path)
    return pd.read_csv(p) if p.exists() else pd.DataFrame(columns=["version", "clip"])


def table(df: pd.DataFrame, cols: dict, index: str = "Version") -> str:
    lines = [f"| {index} | " + " | ".join(cols.values()) + " |", "|---|" + "---|" * len(cols)]
    for name, row in df.iterrows():
        cells = ["–" if pd.isna(row.get(c)) else (str(row[c]) if isinstance(row[c], str) else f"{row[c]:.3f}")
                 for c in cols]
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def hits(df: pd.DataFrame, v: str) -> str:
    d = df[df.version == v].dropna(subset=["grounding_hit"])
    return f"{int(d.grounding_hit.sum())}/{len(d)}" if len(d) else "–"


def grounding_section(syn, real, dev) -> str:
    rows = {v: {"syn": hits(syn, v), "real": hits(real, v),
                "dev": (lambda d: f"{int(d.hit.sum())}/{len(d)}" if len(d) else "–")(dev[dev.variant == v])}
            for v in TEXT_VERSIONS}
    return table(pd.DataFrame(rows).T, {"syn": "Synthetic test", "real": "Real test", "dev": "Real dev (tuning)"})


def tracking_section(syn, real) -> str:
    rows = {}
    for v in ["B0"] + TEXT_VERSIONS:
        r = {}
        for name, df in (("syn", syn), ("real", real)):
            d = df[df.version == v]
            if not len(d):
                continue
            r[f"{name}_all"] = d.JF.mean()
            if v != "B0" and "grounding_hit" in d:
                r[f"{name}_hit"] = d[d.grounding_hit == 1].JF.mean()
        rows[v + (" (click)" if v == "B0" else " (text)")] = r
    return table(pd.DataFrame(rows).T, {"syn_all": "Synthetic J&F", "syn_hit": "…grounding right only",
                                        "real_all": "Real J&F", "real_hit": "…grounding right only"})


def mean_by_version(df: pd.DataFrame, versions: list[str], cols) -> pd.DataFrame:
    d = df[df.version.isin(versions)].groupby("version")[[c for c in cols if c in df]].mean()
    return d.reindex([v for v in versions if v in d.index])


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default="configs/B0.yaml", help="unused; kept for the common CLI")
    ap.add_argument("--out", default="results/stage_report.md")
    args = ap.parse_args(argv)

    syn, real = read("results/results.csv"), read("results/real_results.csv")
    fill, dev = read("results/fill_results.csv"), read("results/grounding_dev.csv")
    check = read("results/metric_check.csv")

    parts = ["# Stage-by-stage evaluation", "Generated by `python -m src.stage_report` from the results CSVs. "
             "Do not edit by hand.",
             "## 1. Grounding: did the text prompt pick the right object?",
             "Box IoU > 0.5 with the true object on frame 0. Click prompts (B0) skip this stage.",
             grounding_section(syn, real, dev),
             "## 2. Tracking: how good are the masks?",
             "B0 starts from a correct click, so its J&F is the tracker on its own. For text versions, "
             "the '…grounding right only' column removes grounding misses, which isolates tracking again.",
             tracking_section(syn, real),
             "## 3. Fill: given perfect masks, how good is the fill?",
             "Each fill method on the true masks (`--overlay configs/fill_only.yaml`), synthetic test clips.",
             table(mean_by_version(fill, FILL_VERSIONS, FILL_COLS), FILL_COLS) if len(fill) else "_Not run yet._",
             "## 4. End to end: what the user gets",
             "Full pipeline on the synthetic test set (`results/results.csv`): every stage's errors combined.",
             table(mean_by_version(syn, ["B0", "I1", "I3", "I3b", "I4"] + TEXT_VERSIONS,
                                   {"JF": 0, **FILL_COLS, "spf_total": 0}),
                   {"JF": "J&F ↑", **{k: v for k, v in FILL_COLS.items() if k != "spf_inpaint"}, "spf_total": "Total s/frame ↓"})]
    if len(check):
        cols = {"psnr_mask": "PSNR mask ↑", "ssim": "SSIM ↑", "lpips_mask": "LPIPS mask ↓",
                "flicker": "Flicker ↓", "flicker_raft": "Flicker RAFT ↓"}
        parts += ["## 5. Metric check: fake outputs of known quality",
                  "From `python -m src.metric_check`; see that script for how each case is made.",
                  table(check.groupby("case", sort=False)[list(cols)].mean(), cols, index="Case")]
    Path(args.out).write_text("\n\n".join(parts) + "\n")
    print(Path(args.out).read_text())


if __name__ == "__main__":
    main()
