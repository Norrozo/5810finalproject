"""A plain-language scorecard: five numbers anyone can read, one row per version.

The raw metrics (J&F, LPIPS, RAFT flicker, ...) are exact but hard to read. Each one is
turned into an everyday unit here. Nothing new is measured; every number comes from the
result CSVs, and how it is computed is printed under the table.

  Right object      clips where the text prompt picked the right object (e.g. 7/10)
  Mask accuracy     how much the mask overlaps the true object, in % (J&F x 100)
  Fill score        0 = object still there, 100 = identical to the real background.
                    Per clip: 100 x (1 - LPIPS of our fill / LPIPS of not removing it),
                    where "not removing it" comes from src/metric_check.py.
  Steadiness        how much the filled area flickers compared with the real video:
                    1.0x = as steady as real footage, 2x = twice as jumpy.
  Speed             seconds per frame on our Mac (M5). A 60-frame clip takes 60 x that.

    python -m src.scorecard        # writes results/scorecard.md
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

NAMES = {  # what each version is, in a few words
    "B0": "click, Telea fill (baseline)", "I1": "B0 + bigger mask", "I2": "text prompt",
    "I2b": "text + CLIP re-rank", "I2c": "text, asks if unsure", "I3": "our flow fill",
    "I3b": "our flow fill, capped", "I4": "ProPainter fill", "I5": "I2c + re-detection",
    "I5b": "I5, fixed check", "I8": "click selects whole object",
}


def read(path: str) -> pd.DataFrame:
    p = Path(path)
    return pd.read_csv(p) if p.exists() else pd.DataFrame(columns=["version", "clip"])


def fill_score(df: pd.DataFrame, check: pd.DataFrame) -> pd.Series:
    """Per-row fill score from LPIPS, scaled between 'not removed' (0) and perfect (100)."""
    base = check[check.case == "not_removed"].set_index("clip").lpips_mask
    return 100 * (1 - df.lpips_mask / df["clip"].map(base))


def summarize(df: pd.DataFrame, check: pd.DataFrame, versions: list[str]) -> pd.DataFrame:
    df = df[df.version.isin(versions)].copy()
    if "lpips_mask" in df and len(check):
        df["fill"] = fill_score(df, check)
    if "flicker_raft" in df:
        df["steady"] = df.flicker_raft / df.flicker_raft_ref
    rows = {}
    for v in [v for v in versions if v in set(df.version)]:
        d = df[df.version == v]
        g = d.grounding_hit.dropna() if "grounding_hit" in d else pd.Series(dtype=float)
        spf = d.spf_total.mean() if "spf_total" in d else float("nan")
        rows[v] = {
            "What": NAMES.get(v, ""),
            "Right object": f"{int(g.sum())}/{len(g)}" if len(g) else "(clicked)",
            "Mask accuracy": f"{100 * d.JF.mean():.0f}%",
            "Fill score": f"{d.fill.mean():.0f}/100" if "fill" in d and d.fill.notna().any() else "–",
            "Steadiness": f"{d.steady.mean():.1f}x" if "steady" in d and d.steady.notna().any() else "–",
            "Speed": f"{spf:.2f} s/frame" if spf == spf else "–",
        }
    return pd.DataFrame(rows).T


def to_md(df: pd.DataFrame) -> str:
    if df.empty:
        return "_No results yet._"
    cols = list(df.columns)
    lines = ["| Version | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
    lines += [f"| {v} | " + " | ".join(str(r[c]) for c in cols) + " |" for v, r in df.iterrows()]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default="configs/B0.yaml", help="unused; kept for the common CLI")
    ap.add_argument("--out", default="results/scorecard.md")
    args = ap.parse_args(argv)
    check = read("results/metric_check.csv")
    order = ["B0", "I1", "I2", "I2b", "I2c", "I3", "I3b", "I4", "I5", "I5b", "I8"]
    parts = [
        "# Scorecard", "Generated by `python -m src.scorecard` from the result CSVs. Do not edit by hand.",
        "**How to read it.** *Right object*: clips where the text prompt picked the right thing. "
        "*Mask accuracy*: overlap with the true object. *Fill score*: 0 = object still there, "
        "100 = identical to the real background. *Steadiness*: flicker compared with the real video "
        "(1.0x = as steady as real footage). *Speed*: on a MacBook (M5); seconds per frame (a 60-frame clip takes 60 times that).",
        "## Pasted benchmark (10 clips, the true background is known)",
        to_md(summarize(read("results/results.csv"), check, order)),
        "## Fill only (every fill method gets the perfect mask; speed = fill step only)",
        to_md(summarize(read("results/fill_results.csv"), check, ["B0", "I1", "I3", "I3b", "I4"])
              .drop(columns=["Right object", "Mask accuracy"], errors="ignore")),
        "## Real videos (10 clips; only the mask can be scored)",
        to_md(summarize(read("results/real_results.csv"), check, order)
              .drop(columns=["Fill score", "Steadiness"], errors="ignore")),
    ]
    Path(args.out).write_text("\n\n".join(parts) + "\n")
    print(Path(args.out).read_text())


if __name__ == "__main__":
    main()
